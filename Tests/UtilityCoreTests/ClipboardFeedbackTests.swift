import AppKit
import CryptoKit
import Testing
import UtilityCore
@testable import PocketUtilities

struct ClipboardFeedbackTests {
    @Test func feedbackFollowsCompleteWriteAndHonorsSettingChanges() throws {
        let settings = SettingsStore(defaults: nil)
        let store = ClipboardStore(settings: settings, directory: FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString))
        store.configure()
        let text = String(repeating: "large clipboard entry\n", count: 100_000)
        store.insert(ClipboardPayload(entries: [[NSPasteboard.PasteboardType.string.rawValue: Data(text.utf8)]]), preview: "Large entry", kind: "Text")
        let item = try #require(store.items.first)
        let board = NSPasteboard.withUniqueName()
        defer { board.releaseGlobally() }
        var feedbackCount = 0
        var writeCount = 0
        let monitor = ClipboardMonitor(settings: settings, store: store, pasteboard: board, copyFeedback: {
            #expect(writeCount > 0)
            feedbackCount += 1
        }, writeObjects: { _, objects in
            // Inspect the complete large payload before reporting a successful write.
            #expect(objects.count == 1)
            #expect(objects.first?.string(forType: .string) == text)
            #expect(objects.first?.types.contains(NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")) == true)
            #expect(feedbackCount == (writeCount == 0 ? 0 : 1))
            writeCount += 1
            return true
        })
        try monitor.restore(item)
        #expect(feedbackCount == 1)
        settings.value.clipboardCopySoundEnabled = false
        try monitor.restore(item)
        #expect(writeCount == 2)
        #expect(feedbackCount == 1)
        settings.value.clipboardCopySoundEnabled = true
        try monitor.restore(item)
        #expect(feedbackCount == 2)
        #expect(writeCount == 3)
    }

    @Test func failedWritesAndUnavailablePayloadsStaySilent() throws {
        let settings = SettingsStore(defaults: nil)
        let store = ClipboardStore(settings: settings, directory: FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString))
        store.configure()
        store.insert(ClipboardPayload(entries: [[NSPasteboard.PasteboardType.string.rawValue: Data("test".utf8)]]), preview: "Test", kind: "Text")
        let item = try #require(store.items.first)
        let board = NSPasteboard.withUniqueName()
        defer { board.releaseGlobally() }
        var feedbackCount = 0
        var writeCount = 0
        let monitor = ClipboardMonitor(settings: settings, store: store, pasteboard: board,
            copyFeedback: { feedbackCount += 1 }, writeObjects: { _, _ in
                writeCount += 1
                return false
            })
        #expect(throws: UtilityError.self) { try monitor.restore(item) }
        #expect(writeCount == 1)
        #expect(feedbackCount == 0)
        #expect(store.items.first?.date == item.date)
        store.delete(item.id)
        #expect(throws: UtilityError.self) { try monitor.restore(item) }
        #expect(writeCount == 1)
        #expect(feedbackCount == 0)
    }

    @Test(arguments: [false, true]) func captureFeedbackFollowsStorageAndHonorsSetting(persistent: Bool) throws {
        let directory = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
        defer { try? FileManager.default.removeItem(at: directory) }
        let settings = SettingsStore(defaults: nil)
        settings.value.clipboardPersistent = persistent
        let key = SymmetricKey(size: .bits256)
        let store = ClipboardStore(settings: settings, directory: directory, keyProvider: { key })
        store.configure()
        let payload = ClipboardPayload(entries: [[NSPasteboard.PasteboardType.string.rawValue: Data(repeating: 65, count: 2_000_000)]])
        let board = NSPasteboard.withUniqueName()
        defer { board.releaseGlobally() }
        var feedbackCount = 0
        let monitor = ClipboardMonitor(settings: settings, store: store, pasteboard: board, copyFeedback: {
            #expect(store.error == nil)
            #expect(store.items.count == 1)
            if let item = store.items.first {
                #expect((try? store.payload(for: item).entries) == payload.entries)
            }
            if persistent {
                let reloaded = ClipboardStore(settings: settings, directory: directory, keyProvider: { key })
                reloaded.configure()
                #expect(reloaded.error == nil)
                #expect(reloaded.items == store.items)
                if let item = reloaded.items.first {
                    #expect((try? reloaded.payload(for: item).entries) == payload.entries)
                }
            }
            feedbackCount += 1
        })
        monitor.recordCapture(payload, preview: "Large entry", kind: "Text")
        #expect(feedbackCount == 1)
        settings.value.clipboardCopySoundEnabled = false
        monitor.recordCapture(payload, preview: "Large entry", kind: "Text")
        #expect(feedbackCount == 1)
        settings.value.clipboardCopySoundEnabled = true
        monitor.recordCapture(payload, preview: "Large entry", kind: "Text")
        #expect(feedbackCount == 2)
        #expect(store.items.count == 1)
        settings.value.clipboardMaxMB = 1
        monitor.recordCapture(payload, preview: "Too large", kind: "Text")
        #expect(store.items.isEmpty)
        #expect(feedbackCount == 2)
        store.error = "Storage unavailable"
        monitor.recordCapture(payload, preview: "Unavailable", kind: "Text")
        #expect(feedbackCount == 2)
    }

    @Test func failedIndexWriteDoesNotPlayCaptureFeedback() throws {
        let directory = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
        defer { try? FileManager.default.removeItem(at: directory) }
        let settings = SettingsStore(defaults: nil)
        settings.value.clipboardPersistent = true
        let store = ClipboardStore(settings: settings, directory: directory, keyProvider: { SymmetricKey(size: .bits256) })
        store.configure()
        #expect(store.error == nil)
        let index = directory.appendingPathComponent("index.enc")
        try FileManager.default.removeItem(at: index)
        try FileManager.default.createDirectory(at: index, withIntermediateDirectories: false)
        let board = NSPasteboard.withUniqueName()
        defer { board.releaseGlobally() }
        var feedbackCount = 0
        let monitor = ClipboardMonitor(settings: settings, store: store, pasteboard: board, copyFeedback: { feedbackCount += 1 })
        monitor.recordCapture(ClipboardPayload(entries: [[NSPasteboard.PasteboardType.string.rawValue: Data("test".utf8)]]), preview: "Test", kind: "Text")
        #expect(store.error != nil)
        #expect(feedbackCount == 0)
    }

    @Test func legacyPreferencesSurviveAndSoundChoicePersists() throws {
        let suite = "ClipboardFeedbackTests.\(UUID().uuidString)"
        let defaults = try #require(UserDefaults(suiteName: suite))
        defer { defaults.removePersistentDomain(forName: suite) }
        var legacy = Preferences.defaults
        legacy.clipboardLimit = 230
        legacy.pasteImmediately = true
        legacy.excludedApps = "example.private"
        let data = try JSONEncoder().encode(legacy)
        let json = try #require(JSONSerialization.jsonObject(with: data) as? [String: Any])
        #expect(json["clipboardCopySound"] == nil)
        defaults.set(data, forKey: "preferences")
        let settings = SettingsStore(defaults: defaults)
        #expect(settings.value.clipboardCopySoundEnabled)
        #expect(settings.value.clipboardLimit == 230)
        #expect(settings.value.pasteImmediately)
        #expect(settings.value.excludedApps == "example.private")
        settings.value.clipboardCopySoundEnabled = false
        #expect(!SettingsStore(defaults: defaults).value.clipboardCopySoundEnabled)
        settings.value.clipboardCopySoundEnabled = true
        #expect(SettingsStore(defaults: defaults).value.clipboardCopySoundEnabled)
    }
}
